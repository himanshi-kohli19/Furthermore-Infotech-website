function escapeXml(value) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function robotsTxt() {
  const crawlerGroups = searchAndAiCrawlers
    .map((crawler) => `User-agent: ${crawler}\nAllow: /`)
    .join("\n\n");

  return `# Generated by scripts/generate-discovery-files.mjs
# Public crawler policy for search engines, AI search, and user-directed AI browsing.

User-agent: *
Allow: /

${crawlerGroups}

Sitemap: ${absoluteSiteUrl("/sitemap.xml")}
`;
}

function sitemapXml() {
  const urls = siteConfig.indexableRoutes
    .map((route) => {
      const images =
        route.path === "/"
          ? importantImages
              .map(
                (image) => `    <image:image>
      <image:loc>${escapeXml(image.loc)}</image:loc>
      <image:title>${escapeXml(image.title)}</image:title>
    </image:image>`
              )
              .join("\n")
          : "";

      return `  <url>
    <loc>${escapeXml(absoluteSiteUrl(route.path))}</loc>
    <lastmod>${siteConfig.lastModified}</lastmod>
    <changefreq>${route.changeFrequency}</changefreq>
    <priority>${route.priority}</priority>
${images}
  </url>`;
    })
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urls}
</urlset>
`;
}

function sitemapTxt() {
  return `${siteConfig.indexableRoutes
    .map((route) => absoluteSiteUrl(route.path))
    .join("\n")}\n`;
}

